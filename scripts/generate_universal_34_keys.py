#!/usr/bin/env python3
"""Generate universal-34-keys from the TOTEM keymap."""

import argparse
from pathlib import Path
import re

from keymap_geometry import SWEEP_GEOMETRY, TOTEM_GEOMETRY
from keymap_svg import render

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "config"
DIAGRAMS = ROOT / "docs/keymap"
# Indexed by Cradio logical position, with values in TOTEM logical positions.
# Three rows of 10, then the inner two thumbs on each half.
UNIVERSAL_TO_TOTEM = (
    *range(10),
    *range(10, 20),
    *range(21, 31),
    33, 34, 35, 36,
)
TOTEM_TO_UNIVERSAL = {position: index for index, position in enumerate(UNIVERSAL_TO_TOTEM)}
TOTEM_KEY_COUNT = 38

COMMENTS = re.compile(r"//[^\n]*|/\*.*?\*/", re.DOTALL)
BINDINGS = re.compile(r"bindings\s*=\s*<([^<>]*)>\s*;")
POSITION_PROPERTY = re.compile(r"([\w-]*key-positions)\s*=\s*<([^<>]*)>\s*;")
SOFT_OFF = re.compile(r"^        hold_soft_off_3s: hold_soft_off_3s \{[^{}]*\};\n", re.M)


def translate_positions(match):
    name, values = match.groups()
    positions = [int(value) for value in values.split()]
    if any(not 0 <= position < TOTEM_KEY_COUNT for position in positions):
        raise ValueError(f"{name} contains an invalid TOTEM position")
    if name not in {"key-positions", "hold-trigger-key-positions"}:
        raise ValueError(f"Unhandled position property: {name}")

    translated = dict.fromkeys(
        TOTEM_TO_UNIVERSAL[position] for position in positions if position in TOTEM_TO_UNIVERSAL
    )
    if not translated or (name == "key-positions" and len(translated) != len(positions)):
        raise ValueError(f"{name} needs an explicit universal-34-keys mapping: {values.strip()}")
    return f"{name} = <{' '.join(map(str, translated))}>;"


def split_bindings(body):
    return re.split(r"\s+(?=&[a-zA-Z_])", body.strip())


def translate_layer(match):
    bindings = split_bindings(match[1])
    if len(bindings) != TOTEM_KEY_COUNT or not all(binding.startswith("&") for binding in bindings):
        raise ValueError(f"Expected {TOTEM_KEY_COUNT} TOTEM bindings in each layer")

    projected = [bindings[position] for position in UNIVERSAL_TO_TOTEM]
    rows = ("  ".join(projected[start:end]) for start, end in
            ((0, 10), (10, 20), (20, 30), (30, 34)))
    return "bindings = <\n" + "".join(f"                {row}\n" for row in rows) + "            >;"


def generate(source):
    source = COMMENTS.sub("", source)
    # Soft-off is wired to a TOTEM side key and its shield provides wake sources.
    source, removed = SOFT_OFF.subn("", source)
    if removed != 1:
        raise ValueError("Expected the TOTEM-only soft-off behavior")
    source = POSITION_PROPERTY.sub(translate_positions, source)
    shared, marker, layers = source.partition('compatible = "zmk,keymap";')
    if not marker:
        raise ValueError("Missing ZMK keymap node")
    layers, count = BINDINGS.subn(translate_layer, layers)
    if not count or "&hold_soft_off_3s" in shared + layers or "&soft_off" in shared + layers:
        raise ValueError("Missing layer bindings or unexpected universal-34-keys soft-off reference")
    output = re.sub(r"\n{3,}", "\n\n", "\n".join(
        line.rstrip() for line in (shared + marker + layers).splitlines()
    )).strip()
    return "// Generated by scripts/generate_universal_34_keys.py from config/totem.keymap.\n\n" + output + "\n"


def diagram_layers(keymap):
    layers = COMMENTS.sub("", keymap).split('compatible = "zmk,keymap";', 1)[1]
    names = re.findall(r'label\s*=\s*"([^"]+)";', layers)
    bindings = [split_bindings(match[1]) for match in BINDINGS.finditer(layers)]
    if len(names) != len(bindings):
        raise ValueError("Expected a label for each keymap layer")
    return list(zip(names, bindings))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    try:
        totem = (CONFIG / "totem.keymap").read_text(encoding="utf-8")
        universal = generate(totem)
        outputs = {CONFIG / "cradio.keymap": universal}
        for slug, title, keymap, geometry, key_size in (
            ("totem", "TOTEM", totem, TOTEM_GEOMETRY, (86, 81)),
            ("universal-34-keys", "Ferris Sweep · universal-34-keys", universal, SWEEP_GEOMETRY, (82, 76)),
        ):
            layers = diagram_layers(keymap)
            names = [name for name, _ in layers]
            for name, bindings in layers:
                layer = "nav" if name == "NAVI" else name.lower()
                outputs[DIAGRAMS / f"{slug}-{layer}.svg"] = render(
                    title, name, bindings, names, geometry, key_size
                )
        for path, content in outputs.items():
            path.write_text(content, encoding="utf-8")
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
